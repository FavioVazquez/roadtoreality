#!/usr/bin/env python3
"""Writes REPORT.md from results.json (called at the end of fit.py; can be run on its own)."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = {'1': '1 circle+free equant, circular Earth', '1b': '1b circle+bisected equant, circular Earth',
         '2': '2 Mars ellipse, circular Earth', '3': '**3 two Kepler ellipses**',
         '1c': '1c circle+free equant, Kepler Earth', '1cb': '1cb circle+bisected equant, Kepler Earth'}


def main():
    r = json.load(open(os.path.join(HERE, 'results.json')))
    M, lg, kt, ph = r['models'], r['log'], r['kepler_test'], r['post_hoc']
    e3 = M['3']['elements']

    def v(n, nd, ang=False):
        q = e3[n]
        u = '°' if ang else ''
        return f"{q['value']:.{nd}f}{u} ± {q['sigma']:.{nd}f}{u}"

    trials = sorted({(t['PM'], t['PE'], t['cost']) for t in lg['two_circle_alias_trials']}, key=lambda q: q[2])
    ratio = trials[1][2] / trials[0][2]
    peaks = ', '.join(f'{p:.4f}' for p in lg['mean_motion_peaks_deg_per_day'][:4])
    asc = ', '.join(f'{a:.1f}' for a in lg['ascending_crossings_helio_lon_deg'])
    L = []
    w = L.append
    w('# Mars orbit from Tycho\'s positions — blind fit (REPORT)\n')
    w('Generated by `report.py` from `results.json` (both produced by `python fit.py`). Protocol: `PLAN.md` '
      '(sections 1–8 plus Amendment A, all written before any fit). Units: Earth\'s a; frame: mean ecliptic and '
      'equinox J1590.0; epoch J1590.0 = JD(TT) 2301792.5. All residuals are observed − model in arcmin; longitude '
      'residuals are multiplied by cos b.\n')
    w('**Blindness statement.** I know roughly what the modern orbits of Mars and Earth are. That knowledge is not used '
      'in any starting value, bound, prior or check. Starting values came from the data: '
      f"{len(lg['oppositions_found'])} oppositions from the retrograde arcs (robust cubic through the retrograde rows); "
      f"mean-motion aliases from the opposition longitudes ({peaks} … °/d); synodic period {lg['synodic_period_days']} d; "
      f"two-circle fits of each alias pair chose P_M ≈ {trials[0][0]:.0f} d and P_E ≈ {trials[0][1]:.0f} d (next-best pair "
      f"{ratio:.2f}× the cost); node from the ascending latitude zero-crossings (heliocentric {asc}°; circular "
      'median used, the 125° crossing is an outlier); inclination from a latitude-only fit. Light time and annual '
      'aberration are modelled from each model\'s own orbits, with Earth\'s a = 499.005 light-seconds (the only '
      f"external constant). Precession self-test: {lg['precession_selftest_arcsec_per_yr']}\"/yr.\n")

    w('## Model 3: two Kepler ellipses (frozen in ORBIT.json)\n')
    w(f"σ = the larger of formal (scaled by χ²_red = {M['3']['reduced_chi2']}) and bootstrap (300 resamples, seed 1590). "
      'Both are listed in ORBIT.json.\n')
    w('| | Mars | Earth |\n|---|---|---|')
    w(f"| a | {v('a', 6)} | 1 (unit) |")
    w(f"| e | {v('e', 6)} | {e3['eE']['value']:.6f} ± {e3['eE']['sigma']:.6f} |")
    w(f"| ϖ (longitude of perihelion) | {v('varpi', 3, True)} | {e3['varpiE']['value']:.2f}° ± {e3['varpiE']['sigma']:.2f}° |")
    w(f"| Ω | {v('Om', 3, True)} | n/a |")
    w(f"| i | {v('inc', 4, True)} | 0 (reference plane) |")
    w(f"| P (sidereal) | {v('P', 4)} d | {e3['PE']['value']:.4f} ± {e3['PE']['sigma']:.4f} d |")
    w(f"| L0 (mean longitude at J1590.0) | {v('L0', 4, True)} | {e3['LE0']['value']:.4f}° ± {e3['LE0']['sigma']:.4f}° |")
    k3 = ph['kepler_third_law']
    w(f"\nKepler's third law was **not** imposed: a³ = {k3['a3']} and (P/P_E)² = {k3['(P/PE)^2']}.\n")

    w('## Model comparison\n')
    w(f"\"Common\" means the {r['common_n']} rows retained by all six models. \"Near opposition\" means elongation ≥ "
      f"{lg['near_opposition_threshold_deg']:.0f}° from model 3's Sun; the near/elsewhere columns use model 3's "
      f"{r['clean_n']} clean rows.\n")
    w('| model | params | retained | RMS lon / lat (common) | median \\|lon\\| / \\|lat\\| (common) | RMS lon near opp. / elsewhere | '
      'χ²_red | BIC (common) | largest systematic lon | 2nd harmonic lon |')
    w('|---|---|---|---|---|---|---|---|---|---|')
    for m in ('1', '1b', '2', '3', '1c', '1cb'):
        x = M[m]; c = x['common']; s = x['systematics_clean']
        npar = len([k for k in x['elements'] if 'sigma' in x['elements'][k]])
        w(f"| {NAMES[m]} | {npar} | {x['n_retained']} | {c['rms_lon']:.2f} / {c['rms_lat']:.2f} | "
          f"{c['med_abs_lon']:.2f} / {c['med_abs_lat']:.2f} | {x['clean_near_opp']['rms_lon']:.2f} / "
          f"{x['clean_elsewhere']['rms_lon']:.2f} | {x['reduced_chi2']} | {x['BIC_common']} | "
          f"{s['systematic_lon']}′ | {s['harm_lon_A2']}′ |")
    best = min(('1', '2', '3'), key=lambda m: M[m]['BIC_common'])
    others = sorted(M[m]['BIC_common'] for m in M if m != best)
    w(f"\nPre-registered decision (BIC on the common set, noise scale from model 3): **model {best} wins**, "
      f"with ΔBIC = {others[0] - M[best]['BIC_common']:.0f} over the next-best model (decisive). Elements and σ for "
      'models 1, 1b, 2, 1c and 1cb are in ORBIT.json.\n')
    w('**Largest systematic pattern in each model.** The measure is the largest |median| longitude residual over 12 '
      'bins of Mars\'s mean anomaly (from model 3) and over the apparitions, on model 3\'s clean rows:')
    for m in ('1', '1b', '2', '3', '1c', '1cb'):
        s = M[m]['systematics_clean']
        w(f"- {m}: bins {s['max_bin_lon'][1]:+.1f}′ at M ≈ {s['max_bin_lon'][0]}°; apparition {s['max_app_lon'][1]:+.1f}′ "
          f"({s['max_app_lon'][0]}); latitude bins {s['max_bin_lat'][1]:+.1f}′ at M ≈ {s['max_bin_lat'][0]}°; "
          f"harmonics A1/A2 = {s['harm_lon_A1']}′/{s['harm_lon_A2']}′.")
    w('\nA circular Earth with uniform motion about its centre (models 1, 1b and 2) gives 15–20′ RMS. Its eccentricity '
      'cannot fit Earth\'s longitudes and distances at once. With Earth on a Kepler ellipse (1c, 1cb), the equant still '
      'leaves an octant-shaped (2nd harmonic) error near M ≈ 45° and 315°. Only the Mars ellipse brings the fit down to '
      'the measurement noise.\n')
    w('Figures: `fig_resid_vs_time.png` and `fig_resid_vs_anomaly.png` show residuals for models 1, 1c, 2 and 3 and '
      'for the two Kepler-style tests. `fig_posthoc_opposition_helio.png` is post hoc (see below).\n')

    a8 = r['answer_8arcmin']
    w('## Kepler\'s 8′ question\n')
    w(f"**Answer: {'YES' if a8['YES'] else 'NO'}.** By the pre-registered rule, model 1c (circle + free equant, same "
      f"Kepler Earth as model 3) leaves a systematic longitude error of {a8['systematic_1c']}′; model 3 leaves "
      f"{a8['systematic_3']}′. Model 1, with a circular Earth, leaves {a8['systematic_1']}′. The ellipse removes the "
      'error with either the free or the bisected equant.\n')
    k1, k2 = kt['1c'], kt['1cb']
    w('Kepler-style test (Earth fixed to model 3; the equant\'s longitude parameters fitted to near-opposition rows '
      'only, then R, Ω and i to all of model 3\'s clean rows):')
    w(f"- Free equant: near opposition RMS {k1['near_opp']['rms_lon']}′ (median {k1['near_opp']['med_abs_lon']}′); "
      f"elsewhere RMS {k1['elsewhere']['rms_lon']}′, up to {k1['max_abs_lon_elsewhere']}′.")
    w(f"- Bisected equant: near opposition RMS {k2['near_opp']['rms_lon']}′; elsewhere RMS {k2['elsewhere']['rms_lon']}′, "
      f"up to {k2['max_abs_lon_elsewhere']}′.\n")
    h = ph['near_opp_helio_equiv']
    w('**Post hoc (added after seeing the residuals).** Geocentric residuals near opposition were scaled by Δ/r '
      '(model 3 geometry), which turns them into heliocentric-equivalent errors, the quantity Kepler compared:')
    w(f"- model 3: RMS {h['3']['rms']}′, worst bin {h['3']['max_abs_bin_median']}′;")
    w(f"- free equant (1c): RMS {h['1c']['rms']}′, worst bin {h['1c']['max_abs_bin_median']}′;")
    w(f"- bisected equant (1cb): RMS {h['1cb']['rms']}′, worst bin {h['1cb']['max_abs_bin_median']}′.")
    w('\nThat is several arcminutes, the same size as Kepler\'s 8′. Seen from Earth near opposition, it is amplified '
      'about 2.5–3×.\n')

    w('## Outliers (model 3, 5σ robust rule only)\n')
    w('| session | Δlon (′) | Δlat (′) |\n|---|---|---|')
    for o in r['outliers_model3']:
        w(f"| {o['session']} | {o['dlon']:+.1f} | {o['dlat']:+.1f} |")
    w('\nThe notes below are interpretation, not part of the rule:')
    w('- 1598-03-02V: latitude −14.3° against +2.5° on the following nights, a transcription slip.')
    w('- 1586-09-23V: same JD as 1586-09-24M and −36′ off, about one day of Mars\'s motion (a date convention).')
    w('- 1594-02-14V: +37′, also about one day of motion.\n')
    for m in ('1', '1b', '2', '1c', '1cb'):
        w(f"- Rejected by model {m} (model-dependent): " + ', '.join(o['session'] for o in M[m]['rejected']))
    w('\nA bad model clips good rows. Model 1 rejects five 1593 rows at +66′ to +87′.\n')

    w('## Notes and deviations\n')
    w('- The Huber stage (f_scale = 2) is solved by iteratively reweighted least squares. scipy\'s built-in Huber loss '
      'did not converge here, and the estimator is the same.')
    w('- The Kepler-style test uses model 3\'s clean rows (implementation choice, not in PLAN.md).')
    w('- Post hoc: the Δ/r analysis and its figure, and `post_hoc.curves` in results.json. That curve (model-vs-model '
      'heliocentric longitude) also absorbs each model\'s different Earth, so it is not used for the answer.')
    w(f"- Model 3's χ²_red of {M['3']['reduced_chi2']} means the formal per-row σ are about "
      f"{M['3']['reduced_chi2'] ** 0.5:.1f}× too small. The quoted σ include this, and the bootstrap agrees.")
    w('- Diurnal parallax and refraction are not modelled (the positions are given as geocentric).')
    open(os.path.join(HERE, 'REPORT.md'), 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
